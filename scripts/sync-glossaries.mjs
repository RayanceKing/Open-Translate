// Regenerate from a separately downloaded, pinned upstream checkout. Never execute it.
// Usage: node scripts/sync-glossaries.mjs /absolute/path/to/Open-Translate-Terms
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REVISION = 'b4c8f15eaddb98337151fe4dbdc463eb2aa45330';
const source = process.argv[2];
if (!source || !path.isAbsolute(source)) throw new Error('Provide an absolute path to the pinned upstream checkout');
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (revision !== REVISION) throw new Error(`Expected upstream ${REVISION}, got ${revision}`);
// Reject edited tracked data: this command inspects the checkout, it does not run upstream code.
const dirty = execFileSync('git', ['-C', source, 'status', '--porcelain', '--untracked-files=all'], { encoding: 'utf8' });
if (dirty.trim()) throw new Error('Upstream checkout must be clean');
const read = name => readFile(path.join(source, name), 'utf8');
function csv(text, filename) {
  const rows = []; let row = [], field = '', quoted = false, closed = false;
  text = text.replace(/^﻿+/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i+1] === '"') { field += '"'; i++; }
      else if (c === '"') { quoted = false; closed = true; }
      else field += c;
    } else if (c === '"') {
      if (field.trim() && !closed) { field += c; continue; }
      if (closed) throw new Error(`${filename}: invalid quote`);
      quoted = true; field = '';
    } else if (c === ',' || c === '\n' || c === '\r') {
      row.push(field.trim()); field = ''; closed = false;
      if (c !== ',') { rows.push(row); row = []; if (c === '\r' && text[i+1] === '\n') i++; }
    } else {
      if (closed && !/\s/.test(c)) throw new Error(`${filename}: trailing data after quote`);
      field += c;
    }
  }
  if (quoted) throw new Error(`${filename}: unclosed quote`);
  if (field || row.length || closed) { row.push(field.trim()); rows.push(row); }
  const header = rows.shift();
  if (JSON.stringify(header) !== JSON.stringify(['source','target','tgt_lng'])) throw new Error(`${filename}: unexpected header`);
  return rows.filter(r => r.some(Boolean)).map((r, i) => {
    // One published upstream row has a harmless extra trailing empty column.
    if (r.length === 4 && r[3] === '') r.pop();
    if (r.length < 2 || r.length > 3 || !r[0]) throw new Error(`${filename}: invalid row ${i+2}`);
    return {source:r[0], target:r[1], targetLanguage:r[2] || '*'};
  });
}
const ids = JSON.parse(await read('meta/index.json'));
if (!Array.isArray(ids) || ids.length !== 36 || new Set(ids).size !== ids.length) throw new Error('Unexpected metadata index');
const available = new Set((await readdir(path.join(source, 'glossaries'))).filter(n => n.endsWith('.csv')));
const used = new Set(), libraries = [];
for (const id of ids) {
  if (!/^[\w-]+$/.test(id)) throw new Error(`Invalid id: ${id}`);
  const meta = JSON.parse(await read(`meta/${id}.json`));
  if (meta.id !== id || !Array.isArray(meta.langs) || meta.glossary !== id) throw new Error(`Invalid metadata: ${id}`);
  const entries = [];
  for (const lang of meta.langs) {
    if (!/^[\w-]+$/.test(lang)) throw new Error(`Invalid language: ${lang}`);
    const filename = `${id}${lang === 'auto' ? '' : '_' + lang}.csv`;
    if (!available.has(filename) || used.has(filename)) throw new Error(`Missing or duplicate file: ${filename}`);
    used.add(filename);
    const rows = csv(await read(`glossaries/${filename}`), filename);
    for (const entry of rows) {
      if (lang !== 'auto' && entry.targetLanguage !== '*' && entry.targetLanguage.toLowerCase() !== lang.toLowerCase()) throw new Error(`Incorrect language in ${filename}`);
      if (lang !== 'auto' && entry.targetLanguage === '*') entry.targetLanguage = lang;
      entries.push(entry);
    }
  }
  libraries.push({id, name: meta.i18ns?.['zh-CN']?.name || meta.name, description: meta.i18ns?.['zh-CN']?.description || meta.description || '', langs: meta.langs, entries});
}
if (used.size !== available.size || used.size !== 67) throw new Error(`Unmapped CSV files: ${[...available].filter(n => !used.has(n)).join(', ')}`);
const license = await read('LICENSE');
if (!license.includes('GNU AFFERO GENERAL PUBLIC LICENSE') || !license.includes('Version 3')) throw new Error('Unexpected source license');
const result = `// Generated by scripts/sync-glossaries.mjs. Do not edit.\n// Upstream data is licensed under AGPL-3.0; see GLOSSARY_SOURCE.\nexport const GLOSSARY_SOURCE = ${JSON.stringify({url:'https://github.com/RayanceKing/Open-Translate-Terms', revision:REVISION, license:'AGPL-3.0'}, null, 2)};\nexport const GLOSSARY_LIBRARIES = ${JSON.stringify(libraries)};\n`;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await writeFile(path.join(root, 'extension/lib/glossary-data.js'), result);
console.log(`Generated ${libraries.length} libraries from ${used.size} CSV files`);
